export function alpha2ToName(alpha2: string): string | undefined {
  return ALPHA2_TO_NAME[alpha2.toUpperCase()];
}

export function countryName(code: string): string {
  const upper = code.toUpperCase();
  if (upper.length === 2) {
    return alpha2ToName(upper) ?? upper;
  }
  const alpha2 = numericToAlpha2(upper);
  if (alpha2) {
    return alpha2ToName(alpha2) ?? alpha2;
  }
  return code;
}

