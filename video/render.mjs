// Renders promo.html to an MP4 frame by frame, then muxes in the music track.
//
// Usage:
//   node video/render.mjs                 full render -> video/out/traceiq-promo.mp4
//   node video/render.mjs --stills 2,7.5  just PNG stills at those times
//   node video/render.mjs --fps 24        lower frame rate for a quick draft

import { spawn } from 'node:child_process';
import { existsSync } from 'node:fs';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';

const dir = new URL('.', import.meta.url).pathname;
const args = process.argv.slice(2);
const flag = (name) => (args.includes(name) ? args[args.indexOf(name) + 1] : undefined);
const FPS = Number(flag('--fps') ?? 30);
const stills = flag('--stills')?.split(',').map(Number);

await mkdir(`${dir}out`, { recursive: true });
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1920, height: 1080 }, deviceScaleFactor: 1 });
await page.goto(`file://${dir}promo.html`);
await page.evaluate(() => window.ready);
const duration = await page.evaluate(() => window.DURATION);

async function frameAt(t) {
  await page.evaluate((time) => window.render(time), t);
  return page.screenshot({ type: 'jpeg', quality: 95 });
}

if (stills) {
  for (const t of stills) {
    await page.evaluate((time) => window.render(time), t);
    await page.screenshot({ path: `${dir}out/still-${t}.png` });
    console.log(`still ${t}s`);
  }
  await browser.close();
  process.exit(0);
}

const silent = `${dir}out/traceiq-promo-silent.mp4`;
const ffmpeg = spawn('ffmpeg', [
  '-y', '-loglevel', 'error',
  '-f', 'image2pipe', '-framerate', String(FPS), '-c:v', 'mjpeg', '-i', '-',
  '-c:v', 'libx264', '-preset', 'slow', '-crf', '18', '-pix_fmt', 'yuv420p', '-movflags', '+faststart',
  silent
], { stdio: ['pipe', 'inherit', 'inherit'] });

const total = Math.round(duration * FPS);
for (let i = 0; i < total; i++) {
  const buf = await frameAt(i / FPS);
  if (!ffmpeg.stdin.write(buf)) await new Promise((r) => ffmpeg.stdin.once('drain', r));
  if (i % FPS === 0) process.stdout.write(`\r${Math.round((i / total) * 100)}%`);
}
ffmpeg.stdin.end();
await new Promise((r) => ffmpeg.on('close', r));
await browser.close();
console.log('\rvideo rendered');

// Music is generated by music.py; mux it in when present.
const music = `${dir}out/music.wav`;
if (existsSync(music)) {
  const out = `${dir}out/traceiq-promo.mp4`;
  await new Promise((resolve, reject) => {
    const mux = spawn('ffmpeg', [
      '-y', '-loglevel', 'error', '-i', silent, '-i', music,
      '-c:v', 'copy', '-af', 'loudnorm=I=-14:TP=-1.5:LRA=7', '-ar', '48000', '-c:a', 'aac', '-b:a', '192k', '-shortest', '-movflags', '+faststart', out
    ], { stdio: 'inherit' });
    mux.on('close', (code) => (code === 0 ? resolve() : reject(new Error(`ffmpeg exited ${code}`))));
  });
  console.log(`wrote ${out}`);
} else {
  console.log(`wrote ${silent} (run music.py first to add sound)`);
}
